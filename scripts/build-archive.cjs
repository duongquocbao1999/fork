// Builds src/archive.js — the documented, sourced subset the site ships — from src/data.js.
// Run after editing data:  npm run build
const fs = require('fs');
const path = require('path');
const D = require('./load-data.cjs')();

const doc = D.nodes.filter(n => n.doc);
const keep = new Set(doc.map(n => n.id));
const nodes = doc.map(n => ({
  id: n.id, name: n.name, type: n.type, platform: n.platform, plat: D.PLATFORMS[n.platform],
  date: n.date, approx: n.approx || null, reported: !!n.reported,
  parent: n.parent || null, children: n.children.filter(c => keep.has(c)), depth: n.depth, root: n.root, family: n.family,
  desc: n.desc || '', handle: n.handle || null, ticker: n.ticker || null, aliases: n.aliases || [],
  sources: n.sources, conf: n.conf, relation: n.relation, evidence: n.evidence,
  traits: n.fullTraits, changed: n.changed, mutation: n.mutation,
  descendants: n.descendants, depthBelow: n.depthBelow, forks: n.forks, forks30: n.forks30,
  status: n.status, score: n.score, pathConf: +n.pathConf.toFixed(3)
}));
const out = {
  updated: D.SAMPLE_NOW.toISOString().slice(0, 10),
  families: D.FAMILIES.map(f => ({ id: f.id, name: f.name })),
  traits: D.TRAITS, evidenceKinds: D.EVIDENCE_KINDS, nodes
};
const js = '/* forks — documented archive. Generated by scripts/build-archive.cjs from src/data.js; do not edit by hand. */\nwindow.FORKS_ARCHIVE=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'archive.js'), js);
console.log(`archive: ${nodes.length} objects, ${nodes.filter(n => !n.parent).length} origins, ${(js.length / 1024) | 0} KB`);
