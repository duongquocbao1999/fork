// Builds netlify/lib/upstream.mjs: upstream's system prompt and tool list, read from src/brain.js.
// /api/ask sends the model these and ignores any prompt or tools a caller sends, so the endpoint
// can't be used as a general-purpose model on our key. Run after editing brain.js or data:  npm run build
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
// Just enough of a browser for archive.js + brain.js to load. No fetch, so brain.js stays offline.
const sandbox = { location: { protocol: 'http:', hostname: 'localhost' }, setTimeout, clearTimeout, console };
sandbox.window = sandbox;
vm.createContext(sandbox);
for (const file of ['src/archive.js', 'src/brain.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), sandbox, { filename: file });
}

const B = sandbox.ForksBrain;
if (!B || typeof B.RULES !== 'string' || typeof B.toolSpecs !== 'function') throw new Error('brain.js must expose RULES and toolSpecs');
const tools = B.toolSpecs().map(t => ({
  type: 'function',
  function: { name: t.name, description: t.description, parameters: t.inputSchema || { type: 'object', properties: {} } }
}));

const js = '// Generated by scripts/build-upstream.cjs from src/brain.js; do not edit by hand.\n' +
  `export const SYSTEM = ${JSON.stringify(B.RULES)};\n` +
  `export const TOOLS = ${JSON.stringify(tools, null, 1)};\n`;
fs.mkdirSync(path.join(root, 'netlify', 'lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'netlify', 'lib', 'upstream.mjs'), js);
console.log(`upstream: system prompt ${B.RULES.length} chars, ${tools.length} tools (${tools.map(t => t.function.name).join(', ')})`);
